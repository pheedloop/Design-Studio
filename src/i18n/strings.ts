export function flattenNamespaces(
  groups: Record<string, Readonly<Record<string, string>>>,
): Record<string, string> {
  const flat: Record<string, string> = {};
  for (const [namespace, entries] of Object.entries(groups)) {
    for (const [key, english] of Object.entries(entries)) {
      flat[`${namespace}.${key}`] = english;
    }
  }
  return flat;
}
